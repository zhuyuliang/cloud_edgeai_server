def main():
    po = polib.POFile()
    po.metadata = {
        "Project-Id-Version": "cloud_eai_admin",
        "Language": "en",
        "MIME-Version": "1.0",
        "Content-Type": "text/plain; charset=UTF-8",
        "Content-Transfer-Encoding": "8bit",
        "Plural-Forms": "nplurals=2; plural=(n != 1);",
    }

    # 从源码收集的 msgid 全集（templates {% trans %} + views _()）
    msgids = []
    with open(os.path.join(BASE, "msgid_list.txt"), "r", encoding="utf-8") as f:
        for line in f:
            s = line.rstrip("\n")
            if s:
                msgids.append(s)

    missing = []
    for msgid in msgids:
        if msgid in EN:
            entry = polib.POEntry(msgid=msgid, msgstr=EN[msgid])
        else:
            # 未在词典中：保守处理 —— 英文沿用中文原文，保证不缺 entry
            missing.append(msgid)
            entry = polib.POEntry(msgid=msgid, msgstr=msgid)
        po.append(entry)

    out_dir = os.path.join(BASE, "..", "locale", "en", "LC_MESSAGES")
    out_dir = os.path.normpath(out_dir)
    os.makedirs(out_dir, exist_ok=True)
    po_path = os.path.join(out_dir, "django.po")
    po.save(po_path)
    po.save_as_mofile(os.path.join(out_dir, "django.mo"))

    print("po entries: %d" % len(po))
    print("saved: %s" % po_path)
    if missing:
        print("WARNING - %d msgid(s) without translation (fallback to Chinese):" % len(missing))
        for m in missing:
            print("  " + m)


if __name__ == "__main__":
    main()
