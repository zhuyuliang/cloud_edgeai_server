def read_db_config():
    filepath = ".db.json"
    config_data = None
    for encoding in ["utf-8", "gbk"]:
        try:
            f = open(filepath, 'r', encoding=encoding)
            content = f.read()
            config_data = json.loads(content)
            f.close()
            break
        except Exception as e:
            print("read_db_config() read error:%s,encoding=%s|%s" % (str(e), encoding, str(filepath)))
    if config_data:
        return config_data
    else:
        raise Exception("read_db_config() read config_data error")

